function getLang() {
  // 1. Per-profile setting, 2. global fallback, 3. English
  try {
    const session = JSON.parse(localStorage.getItem('nf_session') || sessionStorage.getItem('nf_session') || 'null');
    if (session) {
      // Use profileKey if available (profile-key.js loaded first), else fall back
      const key = (typeof profileKey === 'function')
        ? profileKey('nf_settings')
        : ('nf_settings__' + session.email);
      const s = JSON.parse(localStorage.getItem(key) || '{}');
      if (s.langDisplay && TRANSLATIONS[s.langDisplay]) return s.langDisplay;
    }
  } catch(e) {}
  return localStorage.getItem('nf_lang') || 'en';
}

function t(key, lang) {
  const l = lang || getLang();
  return (TRANSLATIONS[l] && TRANSLATIONS[l][key]) || (TRANSLATIONS['en'] && TRANSLATIONS['en'][key]) || key;
}

function applyLang(lang) {
  if (!TRANSLATIONS[lang]) return;
  // Store globally as fallback
  localStorage.setItem('nf_lang', lang);
  // Apply to all data-i18n elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const attr = el.getAttribute('data-i18n-attr'); // optional: target placeholder etc.
    const translation = t(key, lang);
    if (attr) {
      el.setAttribute(attr, translation);
    } else {
      el.textContent = translation;
    }
  });
  // Update html lang attr
  document.documentElement.lang = lang;
}

// Auto-apply on every page load
document.addEventListener('DOMContentLoaded', () => applyLang(getLang()));